#!/usr/bin/env python3
"""Resolve guest addresses of KCET hook targets, anchored in the owned ELF.

Hooks are defined by KCET semantics (ADR 0001); their guest addresses must not
be tracked. The default source is the owned ELF plus its Ghidra function map
(tools/kcet_resolver): targets are found by what the code loads and calls, so
the result does not depend on the decompilation. The ignored local file
game/SLES-50282/kcet_hooks.ini is what the runtime override module reads at boot:

- kcet.mouse.bind: the function that binds the SIF RPC client to the PS2 USB
  mouse service (SID 0x80000210);
- kcet.mouse.get_info / read / device_info: the wrappers that call that client
  with RPC functions 1, 2, and 3.

- kcet.net.*: the i.LINK socket wrappers (open, bind, connect, send, recv, recvfrom,
  node_id), found by the service id each one calls (docs/sot/ilink-socket-wrapper-spec.md).

With --decomp-root the same targets are also resolved from the owner's matched
decompilation and must agree with the ELF result (cross-check).

Exit codes: 0 written, 1 resolution failed or inputs missing.
"""

from __future__ import annotations

import argparse
import hashlib
import re
import subprocess
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO_ROOT))

from tools.kcet_resolver.elf_image import load_elf  # noqa: E402
from tools.kcet_resolver.errors import HookResolutionError  # noqa: E402
from tools.kcet_resolver.functions import FunctionMap  # noqa: E402
from tools.kcet_resolver.keyboard import (
    resolve_keyboard_hooks as resolve_keyboard_hooks_from_elf,
)  # noqa: E402
from tools.kcet_resolver.network import resolve_network_hooks  # noqa: E402
from tools.kcet_resolver.mouse import (
    resolve_mouse_hooks as resolve_mouse_hooks_from_elf,
)  # noqa: E402
from tools.kcet_resolver.sound import resolve_sound_hooks  # noqa: E402

DEFAULT_DECOMP_ROOT = REPO_ROOT.parent / "aoe"
DEFAULT_ELF = REPO_ROOT / "game" / "SLES-50282" / "AOK.ELF"
DEFAULT_FUNCTION_MAP = REPO_ROOT / "analysis" / "generated" / "function_map.csv"
MOUSE_SOURCE = Path("src") / "kt_mouse.c"
DEFAULT_OUTPUT = REPO_ROOT / "game" / "SLES-50282" / "kcet_hooks.ini"
USB_MOUSE_RPC_SID = "0x80000210"
MOUSE_RPC_FUNCTIONS = {
    1: "kcet.mouse.get_info",
    2: "kcet.mouse.read",
    3: "kcet.mouse.device_info",
}

FUNCTION_DEFINITION = re.compile(
    r"^[A-Za-z_][\w \t\*]*?\b(func_([0-9A-Fa-f]{6,8}))\s*\([^;{]*\)\s*\{", re.MULTILINE
)


def split_functions(source: str) -> dict:
    """Map each defined function name to (address, body text)."""
    matches = list(FUNCTION_DEFINITION.finditer(source))
    functions = {}
    for index, match in enumerate(matches):
        end = matches[index + 1].start() if index + 1 < len(matches) else len(source)
        functions[match.group(1)] = (
            int(match.group(2), 16),
            source[match.start() : end],
        )
    return functions


def find_single(functions: dict, pattern: re.Pattern, role: str) -> tuple:
    found = [
        (name, address, pattern.search(body))
        for name, (address, body) in functions.items()
        if pattern.search(body)
    ]
    if len(found) != 1:
        raise HookResolutionError(
            f"expected exactly one {role} function, found {len(found)}"
        )
    return found[0]


def resolve_mouse_hooks(source: str) -> dict:
    """Return hook name -> guest address for the KCET USB mouse RPC layer."""
    functions = split_functions(source)
    bind_pattern = re.compile(r"\(\s*&(\w+)\s*,\s*" + re.escape(USB_MOUSE_RPC_SID))
    _, bind_address, bind_match = find_single(functions, bind_pattern, "mouse RPC bind")
    client = bind_match.group(1)
    hooks = {"kcet.mouse.bind": bind_address}
    for rpc_function, hook_name in MOUSE_RPC_FUNCTIONS.items():
        call_pattern = re.compile(
            r"\(\s*&" + re.escape(client) + r"\s*,\s*" + str(rpc_function) + r"\s*,"
        )
        _, address, _ = find_single(functions, call_pattern, hook_name)
        hooks[hook_name] = address
    return hooks


def write_hook_file(output: Path, hooks: dict, source_revision: str) -> None:
    lines = [
        f"# Generated by tools/resolve_kcet_hooks.py from {source_revision}.",
        "# Local only (git-ignored): guest addresses must never be tracked.",
    ]
    lines += [f"{name}=0x{address:08x}" for name, address in sorted(hooks.items())]
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("\n".join(lines) + "\n", encoding="utf-8")


def decomp_revision(decomp_root: Path) -> str:
    result = subprocess.run(
        ["git", "rev-parse", "HEAD"], cwd=decomp_root, capture_output=True, text=True
    )
    return result.stdout.strip() if result.returncode == 0 else "unknown"


def resolve_from_decomp(decomp_root: Path) -> dict:
    source_path = decomp_root / MOUSE_SOURCE
    if not source_path.is_file():
        raise HookResolutionError(f"decompiled mouse source not found: {source_path}")
    return resolve_mouse_hooks(
        source_path.read_text(encoding="utf-8", errors="replace")
    )


def elf_sha1(path: Path) -> str:
    return hashlib.sha1(path.read_bytes()).hexdigest()


def main(argv: list | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Resolve KCET hook addresses into an ignored local file."
    )
    parser.add_argument("--elf", type=Path, default=DEFAULT_ELF)
    parser.add_argument("--function-map", type=Path, default=DEFAULT_FUNCTION_MAP)
    parser.add_argument(
        "--decomp-root",
        type=Path,
        default=None,
        help="also cross-check against the owner's decompilation (must agree)",
    )
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    args = parser.parse_args(sys.argv[1:] if argv is None else argv)
    try:
        for required in (args.elf, args.function_map):
            if not required.is_file():
                raise HookResolutionError(f"required input not found: {required}")
        image = load_elf(args.elf)
        functions = FunctionMap.from_csv(args.function_map)
        hooks = resolve_mouse_hooks_from_elf(image, functions)
        hooks.update(resolve_keyboard_hooks_from_elf(image, functions))
        hooks.update(resolve_network_hooks(image, functions))
        hooks.update(resolve_sound_hooks(image, functions))
        if args.decomp_root is not None:
            if resolve_from_decomp(args.decomp_root) != hooks:
                raise HookResolutionError(
                    "ELF and decompilation resolve different KCET hook addresses"
                )
        write_hook_file(args.output, hooks, f"elf-sha1:{elf_sha1(args.elf)}")
    except HookResolutionError as error:
        sys.stderr.write(f"Error: {error}\n")
        return 1
    print(f"Resolved {len(hooks)} KCET hook(s) into {args.output}")
    return 0


if __name__ == "__main__":
    sys.exit(main())

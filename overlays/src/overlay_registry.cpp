namespace {
using DecompiledFn = void* (*)(void*, void*, void*, void*);
std::unordered_map<uint64_t, DecompiledFn> g_overlay_fns;

struct ExecContext {
    uint8_t* rdram = nullptr;
    R5900Context* ctx = nullptr;
    PS2Runtime* runtime = nullptr;
};
thread_local ExecContext g_current_exec;

uint32_t GetActiveOverlayId(const uint8_t* rdram, uint32_t pc) {
    if (!rdram) return 0;
    uint32_t id_addr = 0x01D98004u;
    if (pc >= 0x01ED7000u && pc < 0x01EE7000u) id_addr = 0x01ED7004u;
    else if (pc >= 0x01F68000u && pc < 0x01F88000u) id_addr = 0x01F68004u;
    uint32_t id = 0;
    std::memcpy(&id, rdram + (id_addr & 0x01FFFFFFu), sizeof(id));
    return id;
}

void DecompiledOverlayDispatcher(uint8_t* rdram, R5900Context* ctx, PS2Runtime* runtime) {
    const uint32_t pc = ctx->pc;
    const uint32_t overlay_id = GetActiveOverlayId(rdram, pc);
    const uint64_t key = (static_cast<uint64_t>(overlay_id) << 32) | pc;
    const auto it = g_overlay_fns.find(key);
    if (it != g_overlay_fns.end() && it->second) {
        const uint32_t a0 = getRegU32(ctx, 4);
        const uint32_t a1 = getRegU32(ctx, 5);
        const uint32_t a2 = getRegU32(ctx, 6);
        const uint32_t a3 = getRegU32(ctx, 7);
        g_current_exec = {rdram, ctx, runtime};
        void* ret = it->second(
            reinterpret_cast<void*>(static_cast<uintptr_t>(a0)),
            reinterpret_cast<void*>(static_cast<uintptr_t>(a1)),
            reinterpret_cast<void*>(static_cast<uintptr_t>(a2)),
            reinterpret_cast<void*>(static_cast<uintptr_t>(a3))
        );
        setReturnU32(ctx, static_cast<uint32_t>(reinterpret_cast<uintptr_t>(ret)));
    }
    ctx->pc = getRegU32(ctx, 31);
}
} // namespace

extern "C" void* overlay_dispatch_guest(uint32_t addr, void* a0, void* a1, void* a2, void* a3) {
    if (!g_current_exec.runtime || !g_current_exec.ctx || !g_current_exec.rdram) return nullptr;
    PS2Runtime* runtime = g_current_exec.runtime;
    if (!runtime->hasFunction(addr)) return nullptr;
    R5900Context* ctx = g_current_exec.ctx;
    uint8_t* rdram = g_current_exec.rdram;
    const uint32_t saved_pc = ctx->pc;
    const uint32_t saved_ra = getRegU32(ctx, 31);
    const uint32_t saved_a0 = getRegU32(ctx, 4);
    const uint32_t saved_a1 = getRegU32(ctx, 5);
    const uint32_t saved_a2 = getRegU32(ctx, 6);
    const uint32_t saved_a3 = getRegU32(ctx, 7);
    ctx->r[4] = _mm_set_epi64x(0, static_cast<int64_t>(static_cast<int32_t>(reinterpret_cast<uintptr_t>(a0))));
    ctx->r[5] = _mm_set_epi64x(0, static_cast<int64_t>(static_cast<int32_t>(reinterpret_cast<uintptr_t>(a1))));
    ctx->r[6] = _mm_set_epi64x(0, static_cast<int64_t>(static_cast<int32_t>(reinterpret_cast<uintptr_t>(a2))));
    ctx->r[7] = _mm_set_epi64x(0, static_cast<int64_t>(static_cast<int32_t>(reinterpret_cast<uintptr_t>(a3))));
    auto fn = runtime->lookupFunction(addr);
    if (fn) fn(rdram, ctx, runtime);
    const uint32_t v0 = getRegU32(ctx, 2);
    ctx->pc = saved_pc;
    ctx->r[31] = _mm_set_epi64x(0, static_cast<int64_t>(static_cast<int32_t>(saved_ra)));
    ctx->r[4] = _mm_set_epi64x(0, static_cast<int64_t>(static_cast<int32_t>(saved_a0)));
    ctx->r[5] = _mm_set_epi64x(0, static_cast<int64_t>(static_cast<int32_t>(saved_a1)));
    ctx->r[6] = _mm_set_epi64x(0, static_cast<int64_t>(static_cast<int32_t>(saved_a2)));
    ctx->r[7] = _mm_set_epi64x(0, static_cast<int64_t>(static_cast<int32_t>(saved_a3)));
    return reinterpret_cast<void*>(static_cast<uintptr_t>(v0));
}

// Hook for func_002240B0: overlay disc loader
// Arg0 (a0): const char* filename in rdram
// Arg1 (a1): uint32_t load_address (e.g. 0x01D98000)
// Return (v0): 1 (success)
void Hook_OverlayLoad(uint8_t* rdram, R5900Context* ctx, PS2Runtime*) {
    const uint32_t name_ptr = getRegU32(ctx, 4);
    const uint32_t load_addr = getRegU32(ctx, 5);

    constexpr uint32_t rdram_size = 0x02000000u;
    const uint32_t name_offset = name_ptr & 0x01FFFFFFu;
    std::string name_lower;
    bool terminated = false;
    if (name_ptr != 0 && name_ptr < rdram_size && name_offset < rdram_size) {
        const uint32_t max_length = std::min(rdram_size - name_offset, 256u);
        for (uint32_t index = 0; index < max_length; ++index) {
            const unsigned char value = rdram[name_offset + index];
            if (value == '\0') {
                terminated = true;
                break;
            }
            name_lower += static_cast<char>(std::tolower(value));
        }
    }

    uint32_t overlay_id = 0;
    if (name_lower.find("mo_ov") != std::string::npos) overlay_id = 2;
    else if (name_lower.find("rmmmem") != std::string::npos) overlay_id = 3;
    else if (name_lower.find("lobby") != std::string::npos) overlay_id = 4;
    else if (name_lower.find("dcomp") != std::string::npos) overlay_id = 5;
    else if (name_lower.find("smenu") != std::string::npos) overlay_id = 6;
    else if (name_lower.find("multim") != std::string::npos) overlay_id = 7;
    else if (name_lower.find("thelp") != std::string::npos) overlay_id = 8;
    else if (name_lower.find("hist") != std::string::npos) overlay_id = 9;

    const uint32_t load_offset = load_addr & 0x01FFFFFFu;
    const bool valid_load_address = load_addr != 0 && load_offset <= rdram_size - 12u;
    const bool loaded = terminated && overlay_id != 0 && valid_load_address;
    if (loaded) {
        // The registry uses this header to select the active guest overlay.
        const uint32_t magic = 0x336F574Du;
        std::memcpy(rdram + load_offset, &magic, sizeof(magic));
        std::memcpy(rdram + load_offset + 4u, &overlay_id, sizeof(overlay_id));
        std::memcpy(rdram + load_offset + 8u, &load_addr, sizeof(load_addr));
    }

    std::cout << "[aoe2] Hook_OverlayLoad: overlay_id=" << overlay_id
              << " at 0x" << std::hex << load_addr << std::dec
              << " loaded=" << loaded << '\n';
    setReturnU32(ctx, loaded ? 1u : 0u);
    ctx->pc = getRegU32(ctx, 31);
}

// Hook for func_0021BFB0: app object vtable[3] tick
// 0x21bfb0: lw $a0, -0x74DC($gp); lw $t9, 0($a0); lw $t9, 0xC($t9); jr $t9
void Hook_AppVtableTick(uint8_t* rdram, R5900Context* ctx, PS2Runtime* runtime) {
    const uint32_t gp = getRegU32(ctx, 28);
    const uint32_t app_slot = (gp - 0x74DCu) & 0x01FFFFFFu;
    uint32_t app_addr = 0;
    std::memcpy(&app_addr, rdram + app_slot, sizeof(app_addr));

    if (app_addr == 0 || app_addr >= 0x02000000u) {
        ctx->pc = getRegU32(ctx, 31);
        return;
    }
    uint32_t vtable_addr = 0;
    std::memcpy(&vtable_addr, rdram + (app_addr & 0x01FFFFFFu), sizeof(vtable_addr));

    if (vtable_addr == 0 || vtable_addr >= 0x02000000u) {
        ctx->pc = getRegU32(ctx, 31);
        return;
    }
    uint32_t tick_fn = 0;
    std::memcpy(&tick_fn, rdram + ((vtable_addr + 12u) & 0x01FFFFFFu), sizeof(tick_fn));

    if (tick_fn == 0 || tick_fn >= 0x02000000u || !runtime->hasFunction(tick_fn)) {
        ctx->pc = getRegU32(ctx, 31);
        return;
    }

    // Set $a0 = app_addr and dispatch
    ctx->r[4] = _mm_set_epi64x(0, static_cast<int64_t>(static_cast<int32_t>(app_addr)));
    ctx->pc = tick_fn;
    (void)runtime->dispatchGuestBranch(rdram, ctx, tick_fn, 0x0021BFBCu, 0x0u, PS2Runtime::GuestBranchKind::IndirectJump, "JR");
}


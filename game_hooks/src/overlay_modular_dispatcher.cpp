// Runtime dispatcher for modular overlays.
// When AOE2_MODULAR_OVERLAYS is enabled, overlay code regions are registered during startup,
// but the functions for each overlay are loaded dynamically on demand when the corresponding
// disc overlay file (e.g. *_CD.BIN) is accessed by the game loader.

#include <aoe2/game_hooks/overlay_dispatcher.hpp>
#include "ps2_runtime.h"

#include <cctype>
#include <iostream>
#include <stdexcept>
#include <string>
#include <string_view>
#include <unordered_map>

#if AOE2_MODULAR_OVERLAYS

// Forward declarations of per-overlay registration functions generated by the pipeline.
void RegisterOverlay_dcomp_cd(PS2Runtime& runtime);
void RegisterOverlay_hist_cd(PS2Runtime& runtime);
void RegisterOverlay_lobby_cd(PS2Runtime& runtime);
void RegisterOverlay_mo_ov_cd(PS2Runtime& runtime);
void RegisterOverlay_multimcd(PS2Runtime& runtime);
void RegisterOverlay_rmmmemcd(PS2Runtime& runtime);
void RegisterOverlay_smenu_cd(PS2Runtime& runtime);
void RegisterOverlay_thelp_cd(PS2Runtime& runtime);

namespace {

using OverlayRegistrar = void (*)(PS2Runtime&);

const std::unordered_map<std::string_view, OverlayRegistrar> kOverlayRegistrars = {
    {"DCOMP_CD.BIN", &RegisterOverlay_dcomp_cd},
    {"HIST_CD.BIN", &RegisterOverlay_hist_cd},
    {"LOBBY_CD.BIN", &RegisterOverlay_lobby_cd},
    {"MO_OV_CD.BIN", &RegisterOverlay_mo_ov_cd},
    {"MULTIMCD.BIN", &RegisterOverlay_multimcd},
    {"RMMMEMCD.BIN", &RegisterOverlay_rmmmemcd},
    {"SMENU_CD.BIN", &RegisterOverlay_smenu_cd},
    {"THELP_CD.BIN", &RegisterOverlay_thelp_cd},
};

std::unordered_map<std::string_view, bool> g_loadedOverlays;

std::string NormalizeOverlayFilename(std::string_view raw) {
    const auto sep = raw.find_last_of("/\\");
    if (sep != std::string_view::npos) {
        raw.remove_prefix(sep + 1);
    }
    const auto semi = raw.find(';');
    if (semi != std::string_view::npos) {
        raw = raw.substr(0, semi);
    }
    std::string normalized;
    normalized.reserve(raw.size());
    for (const char ch : raw) {
        normalized.push_back(static_cast<char>(std::toupper(static_cast<unsigned char>(ch))));
    }
    return normalized;
}

}  // namespace

int RegisterGeneratedOverlays(PS2Runtime& runtime) {
    // Add the 3 standard overlay memory regions so guest memory addresses are recognized.
    if (!runtime.addOverlayRegion(0x1d98000u, 0x52680u, 0x1d98004u))
        throw std::runtime_error("cannot add overlay region 0x1d98000");
    if (!runtime.addOverlayRegion(0x1ed7000u, 0x254u, 0x1ed7004u))
        throw std::runtime_error("cannot add overlay region 0x1ed7000");
    if (!runtime.addOverlayRegion(0x1f68000u, 0x11500u, 0x1f68004u))
        throw std::runtime_error("cannot add overlay region 0x1f68000");

    std::cout << "[aoe2] Modular overlay dispatcher initialized: 3 regions registered, functions deferred\n";
    return 8;
}

namespace aoe2::game_hooks {

bool LoadModularOverlayOnDemand(PS2Runtime& runtime, std::string_view filename) {
    const std::string normalized = NormalizeOverlayFilename(filename);
    auto it = kOverlayRegistrars.find(normalized);
    if (it == kOverlayRegistrars.end()) {
        return false;
    }

    const std::string_view canonical_key = it->first;
    if (g_loadedOverlays[canonical_key]) {
        return true;
    }

    std::cout << "[aoe2] Loading modular overlay on demand: " << canonical_key << "\n";
    it->second(runtime);
    g_loadedOverlays[canonical_key] = true;
    return true;
}

}  // namespace aoe2::game_hooks

#endif  // AOE2_MODULAR_OVERLAYS
